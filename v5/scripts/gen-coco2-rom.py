#!/usr/bin/env python3
"""Generate firmware/lib/devices/coco2_rom.h from toolshed/cocoroms/{extbas11.rom,bas13.rom}."""

import os
import pathlib
import sys


def fmt_c_array(name: str, data: bytes) -> str:
    lines = [f"const byte {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 12):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i : i + 12])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main() -> int:
    v5_root = pathlib.Path(__file__).resolve().parent.parent
    shelf = pathlib.Path(os.environ.get("SHELF", v5_root.parent.parent))
    rom_dir = shelf / "toolshed" / "cocoroms"
    extbas_path = rom_dir / "extbas11.rom"
    bas_path = rom_dir / "bas13.rom"

    for p in (extbas_path, bas_path):
        if not p.is_file():
            sys.stderr.write(f"error: missing ROM file: {p}\n")
            return 1

    extbas = extbas_path.read_bytes()
    bas = bas_path.read_bytes()
    if len(extbas) != 8192 or len(bas) != 8192:
        sys.stderr.write(
            f"error: expected 8192-byte ROMs, got extbas={len(extbas)} bas={len(bas)}\n"
        )
        return 1

    out_path = v5_root / "firmware" / "lib" / "devices" / "coco2_rom.h"
    header = "\n".join(
        [
            "// Auto-generated by scripts/gen-coco2-rom.py from toolshed/cocoroms/{extbas11.rom,bas13.rom}.",
            "#pragma once",
            "",
            "// Stored in XIP flash (.rodata) at zero static SRAM cost; copied into SRAM (ram + 0x10000) on",
            "// core 0 at setup_coco2_basic() BEFORE core 1 enters the Hamster bus loop so core 1 never touches flash.",
            fmt_c_array("kExtBas11RomFlash", extbas),
            "",
            fmt_c_array("kBas13RomFlash", bas),
            "",
        ]
    )
    out_path.write_text(header, encoding="utf-8")
    print(f"wrote {out_path} ({len(extbas)} + {len(bas)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
