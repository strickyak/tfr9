#!/bin/sh
# gen-ports.sh -- generate build/generated/{ports_gen.h,io-map.md} from firmware/engines/ports.tsv.
# Validates: every address is inside $FF00-$FFFF, first <= last, and $FF7F is never used.  POSIX sh + awk.
V5=$(cd "$(dirname "$0")/.." && pwd)
src="$V5/firmware/engines/ports.tsv"
out="${1:-$V5/build/generated}"
mkdir -p "$out" || exit 1
awk -F'\t' -v hdr="$out/ports_gen.h" -v md="$out/io-map.md" '
function hex(s,   i, c, v, d) {            # parse 0x.... (POSIX awk has no strtonum)
  s = tolower(s); sub(/^0x/, "", s); v = 0
  for (i = 1; i <= length(s); i++) { c = substr(s, i, 1); d = index("0123456789abcdef", c) - 1
    if (d < 0) { printf "bad hex: %s\n", s > "/dev/stderr"; bad = 1; return 0 }; v = v * 16 + d }
  return v }
/^#/ || NF == 0 { next }
{ n++; p[n] = $1; e[n] = $2; d[n] = $3; f[n] = hex($4); l[n] = hex($5)
  if (f[n] < 65280 || l[n] > 65535 || f[n] > l[n]) { printf "ports.tsv: bad range on row: %s\n", $0 > "/dev/stderr"; bad = 1 }
  if (f[n] <= 65407 && l[n] >= 65407) { printf "ports.tsv: $FF7F is forbidden: %s\n", $0 > "/dev/stderr"; bad = 1 } }
END {
  if (bad) exit 1
  print "// GENERATED by scripts/gen-ports.sh from firmware/engines/ports.tsv -- do not edit." > hdr
  print "#pragma once\n#include <cstddef>\n#include <cstdint>\nstruct PortRange { const char* profile; const char* engine; const char* device; uint16_t first, last; };\ninline constexpr PortRange kPorts[] = {" > hdr
  for (i = 1; i <= n; i++) printf "  {\"%s\", \"%s\", \"%s\", 0x%04X, 0x%04X},\n", p[i], e[i], d[i], f[i], l[i] > hdr
  print "};\ninline constexpr size_t kNumPorts = sizeof(kPorts) / sizeof(kPorts[0]);" > hdr
  print "# I/O map (generated from firmware/engines/ports.tsv)\n\n| profile | engine | device | range |\n|---|---|---|---|" > md
  for (i = 1; i <= n; i++) printf "| %s | %s | %s | `$%04X`-`$%04X` |\n", p[i], e[i], d[i], f[i], l[i] > md
}' "$src" || { echo "gen-ports: FAILED" >&2; exit 1; }
echo "generated $out/ports_gen.h and io-map.md"
