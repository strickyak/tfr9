#!/bin/sh
# gen-ports.sh -- generate build/generated/{ports_gen.h,io-map.md} from firmware/engines/ports.tsv.
# Validates: all tokens lowercase, every address inside 0xff00..0xffff, first <= last, 0xff7f never used,
# and every `port` row refers to a declared `target`.  POSIX sh + awk.
V5=$(cd "$(dirname "$0")/.." && pwd)
src="$V5/firmware/engines/ports.tsv"
out="${1:-$V5/build/generated}"
mkdir -p "$out" || exit 1
awk -F'\t' -v hdr="$out/ports_gen.h" -v md="$out/io-map.md" '
function hex(s,   i, c, v, d) {            # parse 0x.... (POSIX awk has no strtonum)
  if (s !~ /^0x[0-9a-f]+$/) { printf "ports.tsv:%d: bad hex \"%s\"\n", NR, s > "/dev/stderr"; bad = 1; return 0 }
  sub(/^0x/, "", s); v = 0
  for (i = 1; i <= length(s); i++) { c = substr(s, i, 1); d = index("0123456789abcdef", c) - 1
    v = v * 16 + d }
  return v }
function chk_range(f, l, row) {
  if (f < 65280 || l > 65535 || f > l) { printf "ports.tsv:%d: bad range on row: %s\n", NR, row > "/dev/stderr"; bad = 1 }
  if (f <= 65407 && l >= 65407) { printf "ports.tsv:%d: 0xff7f ($FF7F) is forbidden: %s\n", NR, row > "/dev/stderr"; bad = 1 }
}
/^#/ || NF == 0 { next }
/[A-Z]/ { printf "ports.tsv:%d: uppercase not allowed: %s\n", NR, $0 > "/dev/stderr"; bad = 1 }
$1 == "target" {
  if (NF != 5) { printf "ports.tsv:%d: target needs 5 fields: %s\n", NR, $0 > "/dev/stderr"; bad = 1; next }
  key = $2 "/" $3 "/" $4
  if (seen_tgt[key]++) { printf "ports.tsv:%d: duplicate target %s\n", NR, key > "/dev/stderr"; bad = 1 }
  nt++; t_on[nt] = $2; t_run[nt] = $3; t_for[nt] = $4; t_eng[nt] = $5
  next
}
$1 == "port" {
  if (NF != 7) { printf "ports.tsv:%d: port needs 7 fields: %s\n", NR, $0 > "/dev/stderr"; bad = 1; next }
  np++; p_on[np] = $2; p_run[np] = $3; p_for[np] = $4; p_dev[np] = $5; p_f[np] = hex($6); p_l[np] = hex($7); p_row[np] = $0
  chk_range(p_f[np], p_l[np], $0)
  next
}
$1 == "host" {
  if (NF != 6) { printf "ports.tsv:%d: host needs 6 fields: %s\n", NR, $0 > "/dev/stderr"; bad = 1; next }
  nh++; h_on[nh] = $2; h_eng[nh] = $3; h_dev[nh] = $4; h_f[nh] = hex($5); h_l[nh] = hex($6)
  chk_range(h_f[nh], h_l[nh], $0)
  next
}
$1 == "map" {
  if (NF != 5) { printf "ports.tsv:%d: map needs 5 fields: %s\n", NR, $0 > "/dev/stderr"; bad = 1; next }
  nm++; m_name[nm] = $2; m_dev[nm] = $3; m_f[nm] = hex($4); m_l[nm] = hex($5)
  chk_range(m_f[nm], m_l[nm], $0)
  next
}
{ printf "ports.tsv:%d: unknown record kind \"%s\"\n", NR, $1 > "/dev/stderr"; bad = 1 }
END {
  for (i = 1; i <= np; i++) {
    key = p_on[i] "/" p_run[i] "/" p_for[i]
    if (!seen_tgt[key]) { printf "ports.tsv: port refers to undeclared target %s: %s\n", key, p_row[i] > "/dev/stderr"; bad = 1 }
  }
  if (bad) exit 1
  print "// GENERATED by scripts/gen-ports.sh from firmware/engines/ports.tsv -- do not edit." > hdr
  print "#pragma once\n#include <cstddef>\n#include <cstdint>\n" > hdr

  print "struct TargetSpec { const char* on_host; const char* run_os; const char* for_hw; const char* engine; };" > hdr
  print "inline constexpr TargetSpec kTargets[] = {" > hdr
  for (i = 1; i <= nt; i++)
    printf "  {\"%s\", \"%s\", \"%s\", \"%s\"},\n", t_on[i], t_run[i], t_for[i], t_eng[i] > hdr
  print "};\ninline constexpr size_t kNumTargets = sizeof(kTargets) / sizeof(kTargets[0]);\n" > hdr

  print "struct CorePortRange { const char* on_host; const char* run_os; const char* for_hw; const char* device; uint16_t first, last; };" > hdr
  print "inline constexpr CorePortRange kCorePorts[] = {" > hdr
  for (i = 1; i <= np; i++)
    printf "  {\"%s\", \"%s\", \"%s\", \"%s\", 0x%04X, 0x%04X},\n", p_on[i], p_run[i], p_for[i], p_dev[i], p_f[i], p_l[i] > hdr
  print "};\ninline constexpr size_t kNumCorePorts = sizeof(kCorePorts) / sizeof(kCorePorts[0]);\n" > hdr

  print "struct HostReservedRange { const char* on_host; const char* engine; const char* device; uint16_t first, last; };" > hdr
  print "inline constexpr HostReservedRange kHostReserved[] = {" > hdr
  for (i = 1; i <= nh; i++)
    printf "  {\"%s\", \"%s\", \"%s\", 0x%04X, 0x%04X},\n", h_on[i], h_eng[i], h_dev[i], h_f[i], h_l[i] > hdr
  print "};\ninline constexpr size_t kNumHostReserved = sizeof(kHostReserved) / sizeof(kHostReserved[0]);\n" > hdr

  print "struct MapPortRange { const char* map_name; const char* device; uint16_t first, last; };" > hdr
  print "inline constexpr MapPortRange kMapPorts[] = {" > hdr
  for (i = 1; i <= nm; i++)
    printf "  {\"%s\", \"%s\", 0x%04X, 0x%04X},\n", m_name[i], m_dev[i], m_f[i], m_l[i] > hdr
  print "};\ninline constexpr size_t kNumMapPorts = sizeof(kMapPorts) / sizeof(kMapPorts[0]);" > hdr

  print "# I/O map (generated from firmware/engines/ports.tsv)\n" > md
  print "## Targets (`on ... run ... for ...`)\n\n| on | run | for | engine |\n|---|---|---|---|" > md
  for (i = 1; i <= nt; i++) printf "| %s | %s | %s | `%s` |\n", t_on[i], t_run[i], t_for[i], t_eng[i] > md
  print "\n## Core RP2350 I/O Ranges\n\n| on | run | for | device | range |\n|---|---|---|---|---|" > md
  for (i = 1; i <= np; i++) printf "| %s | %s | %s | %s | `0x%04x`-`0x%04x` |\n", p_on[i], p_run[i], p_for[i], p_dev[i], p_f[i], p_l[i] > md
  print "\n## Host Motherboard Reserved Ranges\n\n| on | engine | device | range |\n|---|---|---|---|" > md
  for (i = 1; i <= nh; i++) printf "| %s | %s | %s | `0x%04x`-`0x%04x` |\n", h_on[i], h_eng[i], h_dev[i], h_f[i], h_l[i] > md
  print "\n## Enhancement Maps\n\n| map | device | range |\n|---|---|---|" > md
  for (i = 1; i <= nm; i++) printf "| %s | %s | `0x%04x`-`0x%04x` |\n", m_name[i], m_dev[i], m_f[i], m_l[i] > md
}' "$src" || { echo "gen-ports: FAILED" >&2; exit 1; }
echo "generated $out/ports_gen.h and io-map.md"
